export function renderTsParamType(prototype, param) {
  if (param.type.includes('*')) {
    if (param.type.includes('double')) {
      return 'Float64Array';
    }

    if (param.type.includes('float')) {
      return 'Float32Array';
    }

    if (param.type.includes('void *')) {
      return usesFloat64VoidArrays(prototype) ? 'Float64Array' : 'Float32Array';
    }
  }

  if (param.type.includes('enum CBLAS_TRANSPOSE')) {
    return '111 | 112 | 113';
  }

  if (param.type.includes('enum CBLAS_UPLO')) {
    return '121 | 122';
  }

  if (param.type.includes('enum CBLAS_DIAG')) {
    return '131 | 132';
  }

  if (param.type.includes('enum CBLAS_SIDE')) {
    return '141 | 142';
  }

  if (
    param.type.includes('int') ||
    param.type.includes('float') ||
    param.type.includes('double') ||
    param.type.includes('size_t') ||
    param.type.includes('CBLAS_INDEX')
  ) {
    return 'number';
  }

  throw new Error(`Unsupported TS parameter type "${param.type}" in ${prototype.cblasName}`);
}

export function renderTsReturnType(prototype) {
  if (prototype.returnType === 'void') {
    return 'void';
  }

  if (
    prototype.returnType === 'float' ||
    prototype.returnType === 'double' ||
    prototype.returnType === 'CBLAS_INDEX'
  ) {
    return 'number';
  }

  throw new Error(`Unsupported TS return type "${prototype.returnType}" in ${prototype.cblasName}`);
}

export function renderGeneratedNativeTypes(routines) {
  const lines = routines.map((routine) => {
    const params = routine.params
      .filter((param) => !param.type.includes('enum CBLAS_ORDER'))
      .map((param) => `${param.name}: ${renderTsParamType(routine, param)}`)
      .join(', ');

    return `  ${routine.wrapperName}(${params}): ${renderTsReturnType(routine)};`;
  });

  return `// This file is auto-generated by scripts/generate-native-glue.mjs.
// Do not edit it manually.

export interface INativeBlas {
${lines.join('\n')}
}
`;
}

export function renderGeneratedNativeTs(routines) {
  const exports = routines.map(
    (routine) => `export const ${routine.wrapperName}: INativeBlas['${routine.wrapperName}'] = nblas.${routine.wrapperName};`
  );

  return `// This file is auto-generated by scripts/generate-native-glue.mjs.
// Do not edit it manually.

import { INativeBlas } from './generated-native-types';

function loadNativeAddon(): INativeBlas {
  try {
    return require('../build/Release/nblas');
  } catch (releaseError) {
    try {
      return require('../build/Debug/nblas');
    } catch {
      const error = new Error('Failed to load the nblas native addon. Run \`npm run build\` first.');
      (error as Error & { cause?: unknown }).cause = releaseError;
      throw error;
    }
  }
}

const nblas = loadNativeAddon();

export default nblas;
${exports.join('\n')}
`;
}

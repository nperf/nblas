function usesFloat64VoidArrays(prototype) {
  return (
    prototype.wrapperName.startsWith('z') ||
    prototype.wrapperName.startsWith('dz') ||
    prototype.wrapperName === 'izamax'
  );
}

function pointerArrayType(prototype, param) {
  if (param.type.includes('float')) {
    return 'Napi::Float32Array';
  }

  if (param.type.includes('double')) {
    return 'Napi::Float64Array';
  }

  if (param.type.includes('void *')) {
    return usesFloat64VoidArrays(prototype) ? 'Napi::Float64Array' : 'Napi::Float32Array';
  }

  throw new Error(`Unsupported pointer parameter type "${param.type}" in ${prototype.cblasName}`);
}

function castType(param) {
  if (param.type.includes('*')) {
    if (param.type.includes('void')) {
      return param.type.includes('const') ? 'const void *' : 'void *';
    }

    if (param.type.includes('float')) {
      return param.type.includes('const') ? 'const float *' : 'float *';
    }

    if (param.type.includes('double')) {
      return param.type.includes('const') ? 'const double *' : 'double *';
    }
  }

  throw new Error(`Unsupported cast type "${param.type}"`);
}

function renderNumberExtractor(jsIndex, param) {
  if (param.type.includes('enum CBLAS_')) {
    const enumType = param.type.replace(/^const\s+/, '');
    return `static_cast<${enumType}>(${`info[${jsIndex}]`}.As<Napi::Number>().Int32Value())`;
  }

  if (param.type.includes('size_t') || param.type.includes('CBLAS_INDEX')) {
    return `static_cast<size_t>(info[${jsIndex}].As<Napi::Number>().Int64Value())`;
  }

  if (param.type.includes('float')) {
    return `static_cast<float>(info[${jsIndex}].As<Napi::Number>().FloatValue())`;
  }

  if (param.type.includes('double')) {
    return `info[${jsIndex}].As<Napi::Number>().DoubleValue()`;
  }

  if (param.type.includes('int')) {
    return `info[${jsIndex}].As<Napi::Number>().Int32Value()`;
  }

  throw new Error(`Unsupported numeric parameter type "${param.type}"`);
}

function renderParamDeclaration(prototype, param, jsIndex) {
  if (param.type.includes('*')) {
    const arrayType = pointerArrayType(prototype, param);
    const cast = castType(param);
    return `  auto ${param.name}Array = info[${jsIndex}].As<${arrayType}>();\n  ${cast} ${param.name} = reinterpret_cast<${cast}>(${param.name}Array.Data());`;
  }

  return `  const ${param.type.replace(/^const\s+/, '')} ${param.name} = ${renderNumberExtractor(jsIndex, param)};`;
}

function renderReturnStatement(prototype, callExpression) {
  if (prototype.returnType === 'void') {
    return `  ${callExpression};\n  return env.Undefined();`;
  }

  if (
    prototype.returnType === 'float' ||
    prototype.returnType === 'double' ||
    prototype.returnType === 'CBLAS_INDEX'
  ) {
    return `  return Napi::Number::New(env, ${callExpression});`;
  }

  throw new Error(`Unsupported return type "${prototype.returnType}" for ${prototype.cblasName}`);
}

export function renderRoutine(prototype) {
  const jsParams = prototype.params.filter((param) => !param.type.includes('enum CBLAS_ORDER'));
  const declarations = jsParams.map((param, jsIndex) => renderParamDeclaration(prototype, param, jsIndex));
  const callArgs = prototype.params.map((param) =>
    param.type.includes('enum CBLAS_ORDER') ? 'CblasRowMajor' : param.name
  );

  return `#include <napi.h>
#include "cblas.h"

Napi::Value ${prototype.wrapperName}(const Napi::CallbackInfo& info) {
  Napi::Env env = info.Env();
${declarations.join('\n')}
${renderReturnStatement(prototype, `${prototype.cblasName}(${callArgs.join(', ')})`)}
}
`;
}

